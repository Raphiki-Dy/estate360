alter table public.units             enable row level security;
alter table public.profiles          enable row level security;
alter table public.access_codes      enable row level security;
alter table public.emergency_alerts  enable row level security;

-- ===== units =====
drop policy if exists "units_select_all_authenticated" on public.units;
create policy "units_select_all_authenticated"
  on public.units for select
  to authenticated
  using (true);   -- everyone signed-in can see the unit list (e.g. /register dropdown)

drop policy if exists "units_admin_write" on public.units;
create policy "units_admin_write"
  on public.units for all
  to authenticated
  using (public.current_user_role() = 'ADMIN')
  with check (public.current_user_role() = 'ADMIN');

-- ===== profiles =====
drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own"
  on public.profiles for select
  to authenticated
  using (id = auth.uid());

drop policy if exists "profiles_select_admin_all" on public.profiles;
create policy "profiles_select_admin_all"
  on public.profiles for select
  to authenticated
  using (public.current_user_role() = 'ADMIN');

drop policy if exists "profiles_select_security_residents" on public.profiles;
create policy "profiles_select_security_residents"
  on public.profiles for select
  to authenticated
  using (public.current_user_role() = 'SECURITY');
  -- security guards need to see resident names/units to respond to alerts

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own"
  on public.profiles for update
  to authenticated
  using (id = auth.uid())
  with check (id = auth.uid() and role = (select role from public.profiles where id = auth.uid()));
  -- residents can edit their own name/phone but NOT self-promote role

drop policy if exists "profiles_admin_write_all" on public.profiles;
create policy "profiles_admin_write_all"
  on public.profiles for all
  to authenticated
  using (public.current_user_role() = 'ADMIN')
  with check (public.current_user_role() = 'ADMIN');

drop policy if exists "profiles_insert_self" on public.profiles;
create policy "profiles_insert_self"
  on public.profiles for insert
  to authenticated
  with check (id = auth.uid());

-- ===== access_codes =====
drop policy if exists "access_codes_resident_select_own" on public.access_codes;
create policy "access_codes_resident_select_own"
  on public.access_codes for select
  to authenticated
  using (resident_id = auth.uid());

drop policy if exists "access_codes_resident_insert_own" on public.access_codes;
create policy "access_codes_resident_insert_own"
  on public.access_codes for insert
  to authenticated
  with check (
    resident_id = auth.uid()
    and unit_id = public.current_user_unit_id()
    and public.current_user_role() = 'RESIDENT'
  );

drop policy if exists "access_codes_resident_update_own" on public.access_codes;
create policy "access_codes_resident_update_own"
  on public.access_codes for update
  to authenticated
  using (resident_id = auth.uid())
  with check (resident_id = auth.uid());
  -- allows residents to REVOKE their own active codes

drop policy if exists "access_codes_security_select_all" on public.access_codes;
create policy "access_codes_security_select_all"
  on public.access_codes for select
  to authenticated
  using (public.current_user_role() = 'SECURITY');
  -- guards can look up any code for manual audit (validation itself goes through the RPC)

drop policy if exists "access_codes_admin_all" on public.access_codes;
create policy "access_codes_admin_all"
  on public.access_codes for all
  to authenticated
  using (public.current_user_role() = 'ADMIN')
  with check (public.current_user_role() = 'ADMIN');

-- ===== emergency_alerts =====
drop policy if exists "alerts_resident_select_own" on public.emergency_alerts;
create policy "alerts_resident_select_own"
  on public.emergency_alerts for select
  to authenticated
  using (resident_id = auth.uid());

drop policy if exists "alerts_resident_insert_own" on public.emergency_alerts;
create policy "alerts_resident_insert_own"
  on public.emergency_alerts for insert
  to authenticated
  with check (
    resident_id = auth.uid()
    and unit_id = public.current_user_unit_id()
    and public.current_user_role() = 'RESIDENT'
  );

drop policy if exists "alerts_security_select_all" on public.emergency_alerts;
create policy "alerts_security_select_all"
  on public.emergency_alerts for select
  to authenticated
  using (public.current_user_role() = 'SECURITY');

drop policy if exists "alerts_security_update_resolve" on public.emergency_alerts;
create policy "alerts_security_update_resolve"
  on public.emergency_alerts for update
  to authenticated
  using (public.current_user_role() = 'SECURITY')
  with check (public.current_user_role() = 'SECURITY');

drop policy if exists "alerts_admin_all" on public.emergency_alerts;
create policy "alerts_admin_all"
  on public.emergency_alerts for all
  to authenticated
  using (public.current_user_role() = 'ADMIN')
  with check (public.current_user_role() = 'ADMIN');

-- ---------------------------------------------------------------------
-- 8. REALTIME
--    Enable realtime replication for emergency_alerts (panic popups) and
--    access_codes (live status updates on the resident's code list).
-- ---------------------------------------------------------------------
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and tablename = 'emergency_alerts'
  ) then
    alter publication supabase_realtime add table public.emergency_alerts;
  end if;

  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and tablename = 'access_codes'
  ) then
    alter publication supabase_realtime add table public.access_codes;
  end if;
end $$;

